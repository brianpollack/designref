#!/usr/bin/env node
/**
 * fetch-icons.mjs — download icon artwork from each library's official source into
 * assets/icon-sets.js.
 *
 *   node scripts/fetch-icons.mjs
 *
 * For every library in assets/icon-libraries.js that has a `source`, it fetches:
 *   - the library's `examples` (the comparison table on icons.html), and
 *   - every #i-<name> used on a concept page whose catalog entry has `icons: '<library>'`.
 * Run it after adding an icon to a demo or an example. Prints one line per icon, then writes
 * the file in one go, so a failed download leaves the previous file untouched.
 *
 * Lucide is not fetched: its icons are pasted into assets/icons.js by hand.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = 'assets/icon-sets.js';
const CONCURRENCY = 6;

/** Load the classic browser scripts that hold the data. */
const sandbox = { window: {} };
vm.createContext(sandbox);
for (const f of ['assets/catalog.js', 'assets/icon-libraries.js']) {
  vm.runInContext(readFileSync(join(ROOT, f), 'utf8'), sandbox, { filename: f });
}
const C = sandbox.window.CATALOG;
const L = sandbox.window.ICON_LIBRARIES.libraries;

/** Icon names each library needs: its examples plus whatever its concept pages reference. */
const wanted = {};
for (const [id, lib] of Object.entries(L)) {
  if (lib.source) wanted[id] = new Set(Object.values(lib.examples ?? {}));
}
for (const section of C.sections) {
  for (const cat of section.categories) {
    for (const k of cat.concepts ?? []) {
      if (!k.icons || !wanted[k.icons]) continue;
      const file = join(ROOT, section.id, cat.id, `${k.id}.html`);
      if (!existsSync(file)) continue;
      for (const [, name] of readFileSync(file, 'utf8').matchAll(/#i-([a-z0-9_-]+)/g)) wanted[k.icons].add(name);
    }
  }
}

/** Turn a fetched file into [viewBox, inner SVG markup]. */
function parse(text, format) {
  if (format === 'svg') {
    const viewBox = text.match(/viewBox="([^"]+)"/)?.[1];
    const inner = text.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    if (!viewBox || !inner) throw new Error('not an SVG');
    return [viewBox, inner];
  }
  if (format === 'carbon-module') {
    // The module's default export is a plain object literal: { elem, attrs, content: [...] }.
    const literal = text.match(/=\s*(\{[\s\S]*\});?\s*\/\/#endregion/)?.[1];
    if (!literal) throw new Error('unexpected @carbon/icons module');
    const icon = vm.runInNewContext(`(${literal})`);
    const attr = a => Object.entries(a).map(([k, v]) => ` ${k}="${v}"`).join('');
    const node = n => `<${n.elem}${attr(n.attrs ?? {})}>${(n.content ?? []).map(node).join('')}</${n.elem}>`;
    return [icon.attrs.viewBox, icon.content.map(node).join('')];
  }
  throw new Error(`unknown format ${format}`);
}

const jobs = Object.entries(wanted).flatMap(([id, names]) => [...names].sort().map(name => ({ id, name })));
const sets = Object.fromEntries(Object.keys(wanted).map(id => [id, {}]));
let done = 0, failed = 0;

async function worker() {
  while (jobs.length) {
    const { id, name } = jobs.shift();
    const { url, format } = L[id].source;
    const src = url.replaceAll('{name}', name);
    try {
      const res = await fetch(src, { signal: AbortSignal.timeout(20000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      sets[id][name] = parse(await res.text(), format);
      console.log(`[${++done}] ✓ ${id}/${name}`);
    } catch (e) {
      failed++;
      console.log(`[${++done}] ✗ ${id}/${name}  ${e.message}  (${src})`);
    }
  }
}
const total = jobs.length;
console.log(`Fetching ${total} icons from ${Object.keys(wanted).length} libraries…`);
await Promise.all(Array.from({ length: CONCURRENCY }, worker));
if (failed) {
  console.log(`\n${failed} of ${total} failed; ${OUT} was not changed.`);
  process.exit(1);
}

// Stable output: libraries in registry order, icons sorted by name.
const body = Object.entries(sets).map(([id, icons]) => {
  const rows = Object.keys(icons).sort().map(n => `    ${JSON.stringify(n)}: ${JSON.stringify(icons[n])},`).join('\n');
  return `  ${JSON.stringify(id)}: {\n${rows}\n  },`;
}).join('\n');
writeFileSync(join(ROOT, OUT), `/**
 * icon-sets.js — icon artwork for the libraries in assets/icon-libraries.js (all but Lucide).
 *
 * GENERATED by \`node scripts/fetch-icons.mjs\`; do not edit by hand.
 * Each icon is [viewBox, inner SVG markup], drawn in currentColor.
 */
window.ICON_SETS = {
${body}
};
`);
console.log(`\nWrote ${OUT}: ${total} icons.`);
